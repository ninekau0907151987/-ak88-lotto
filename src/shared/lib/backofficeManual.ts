export interface AccessEntry {
  /** ชื่อที่แสดง */
  name: string;
  /** ★ URL ทางเข้า */
  path: string;
  /** ชื่อผู้ใช้ */
  username: string;
  /** ★ รหัสผ่านเริ่มต้น */
  defaultPassword: string;
  /** ตำแหน่ง */
  role: string;
  /** ตำแหน่งในระบบ (role label) */
  roleLabel: string;
  /** เข้าได้กี่สิทธิ์ */
  permCount: number;
  /** ทำอะไรได้ */
  can: string[];
  /** ★ ต้องเปลี่ยนรหัสไหม */
  mustChange: boolean;
  /** หมายเหตุ */
  note: string;
}

/**
 * ★ กำหนดรหัสผ่านเริ่มต้น — อ่านจาก env ได้ (fallback เป็นค่าตั้งต้นในฐานข้อมูล)
 */
function envPass(key: string, fallback: string): string {
  try {
    const e = (import.meta as any)?.env;
    if (e && e[key]) return String(e[key]);
  } catch { /* ไม่มี env */ }
  return fallback;
}

